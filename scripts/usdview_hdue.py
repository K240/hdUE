"""Stock OpenUSD 26.03 usdview with a same-process UELibrary owner."""
import json
import os
from pathlib import Path
import sys
import traceback

# Must be configured before any pxr import. Keep add_dll_directory handles alive.
_dll_paths = []
usd_root = Path(os.environ["HDUE_OPENUSD_ROOT"]).resolve()
for directory in (usd_root / "bin", usd_root / "lib"):
    _dll_paths.append(os.add_dll_directory(str(directory)))
sys.path.insert(0, str(usd_root / "lib/python"))

from pxr import Usd, UsdGeom, Usdviewq, Work
from pxr.Usdviewq.qt import QtCore, QtWidgets
from hdue_runtime import Runtime
from camera_controls import install_camera_controls
from picking_controls import install_picking

PLUGIN = "HdUERendererPlugin"
ROOT = Path(__file__).resolve().parent.parent
GAME = ROOT / "out/runtime/Windows/HdUEBackend"


class Launcher(Usdviewq.Launcher):
    def __init__(self):
        super().__init__()
        self.runtime = None
        self.timer = None
        self.controller = None
        self.failure = None
        self.test_result = None
        self.options = None
        self.reported_error = None
        self.materialx_library = None
        self.glass_profile = None
        self.asset_references = None
        self.material_preparation_error = None
        self.residency_preparing = False
        self.reported_asset_warning = None
        self.asset_loading = False
        self.native_camera_applied = False

    def RegisterOptions(self, parser):
        super().RegisterOptions(parser)
        parser.add_argument("--hdue-backend", default=str(GAME / "Binaries/Win64/HdUEBackend.dll"))
        parser.add_argument("--hdue-project", default=str(GAME / "HdUEBackend.uproject"))
        parser.add_argument("--hdue-mode", choices=("realtime", "pathtraced"), default="realtime",
                            help="Initial renderer mode (default: realtime with Lumen)")
        parser.add_argument("--hdue-test-output", type=Path)
        parser.add_argument("--hdue-camera-benchmark", action="store_true",
                            help="Measure continuous camera interaction with the real viewport")
        parser.add_argument("--hdue-scene-check", action="store_true",
                            help="Check any unlit USD scene with the real viewport")
        parser.add_argument("--hdue-viewer-light", choices=("auto", "off"), default="auto",
                            help="Add viewer lights when the scene has no active supported lights")
        parser.add_argument("--hdue-materialx-library", type=Path,
                            help="Cooked MaterialX registry generated by Import-MaterialX.ps1")
        parser.add_argument("--hdue-materialx-check", action="store_true")
        parser.add_argument("--hdue-texture-check", action="store_true")
        parser.add_argument("--hdue-residency-check", action="store_true")
        parser.add_argument("--hdue-opacity-check", action="store_true")
        parser.add_argument("--hdue-glass-profile", type=Path)
        parser.add_argument("--hdue-glass-check", action="store_true")
        parser.add_argument("--hdue-runtime-config", type=Path, help="Prepared project runtime JSON (DLL, uproject and asset catalog)")
        parser.add_argument("--hdue-asset-check", action="store_true")

    def ValidateOptions(self, options):
        super().ValidateOptions(options)
        options.hdue_asset_catalog = None
        if options.hdue_runtime_config:
            config_path=options.hdue_runtime_config.resolve()
            config=json.loads(config_path.read_text(encoding="utf-8-sig"))
            if config.get("version") != 1: raise ValueError("Unsupported hdUE runtime config")
            def resolve_path(key):
                p=Path(config[key]); return str(p if p.is_absolute() else (config_path.parent/p).resolve())
            options.hdue_backend=resolve_path("backend_dll")
            options.hdue_project=resolve_path("runtime_project")
            options.hdue_asset_catalog=resolve_path("asset_catalog")
        if Usd.GetVersion() != (0, 26, 3):
            raise ValueError("hdUE is pinned to OpenUSD 26.03")
        if options.noRender or options.allowAsync:
            raise ValueError("hdUE requires synchronous scene processing and an enabled viewport")
        for path in (options.hdue_backend, options.hdue_project):
            if not Path(path).is_file():
                raise FileNotFoundError(path)
        if options.hdue_test_output:
            if options.hdue_mode != "realtime" or options.quitAfterStartup:
                raise ValueError("The integration test must start in realtime and run its full event loop")
            options.hdue_test_output.mkdir(parents=True, exist_ok=False)
        elif options.hdue_camera_benchmark or options.hdue_scene_check or options.hdue_materialx_check or options.hdue_texture_check or options.hdue_residency_check or options.hdue_opacity_check or options.hdue_glass_check or options.hdue_asset_check:
            raise ValueError("GUI checks require --hdue-test-output")
        if sum((options.hdue_camera_benchmark, options.hdue_scene_check, options.hdue_materialx_check, options.hdue_texture_check, options.hdue_residency_check, options.hdue_opacity_check, options.hdue_glass_check, options.hdue_asset_check))>1:
            raise ValueError("Choose one GUI check")
        if (options.hdue_materialx_check or options.hdue_texture_check or options.hdue_residency_check) and not options.hdue_materialx_library:
            raise ValueError("MaterialX check requires a cooked MaterialX library")
        if options.hdue_glass_check and not options.hdue_glass_profile:
            raise ValueError("Glass check requires --hdue-glass-profile")

    def LaunchPreamble(self, options):
        self.options = options
        os.environ["HDUE_BACKEND_DLL"] = str(Path(options.hdue_backend).resolve())
        # This is the standard LaunchPreamble sequence, with initialization
        # inserted between QApplication and AppController (which may draw).
        Work.SetConcurrencyLimitArgument(options.numThreads)
        if options.clearSettings:
            Usdviewq.AppController.clearSettings()
        app = QtWidgets.QApplication(sys.argv)
        log = options.hdue_test_output / "ue.log" if options.hdue_test_output else None
        self.runtime = Runtime(options.hdue_backend, options.hdue_project, log)
        self.controller = Usdviewq.AppController(options, self.GetResolverContext)
        from asset_controls import AssetReferences
        self.asset_references = AssetReferences(self.controller, options.hdue_asset_catalog)
        self.asset_references.sync()
        if options.hdue_materialx_library:
            from materialx_controls import MaterialXLibrary
            self.materialx_library = MaterialXLibrary(options.hdue_materialx_library, self.controller)
        if options.hdue_glass_profile:
            from glass_controls import GlassProfile
            self.glass_profile = GlassProfile(options.hdue_glass_profile, self.controller)
        # hdUE provides calibrated viewer lights without authoring USD prims.
        # The stock camera light remains available as an explicit override.
        self.controller._dataModel.viewSettings.ambientLightOnly = False
        self.controller._dataModel.viewSettings.domeLightEnabled = False
        self.controller._refreshLightsMenu()
        view = self.controller._stageView
        install_camera_controls(view)
        install_picking(self.controller)
        original = view._handleRendererChanged

        def renderer_changed(renderer_id):
            original(renderer_id)
            self.configure_renderer()

        # Instance hook; installed usdview modules and StageView class stay intact.
        view._handleRendererChanged = renderer_changed
        self.configure_renderer()
        menu = self.controller._mainWindow.menuBar().addMenu("hdUE")
        for label, mode in (("Realtime / Lumen (default)", "realtime"), ("Path Tracer (64 samples)", "pathtraced")):
            action = menu.addAction(label)
            action.triggered.connect(lambda checked=False, mode=mode: self.select_mode(mode))
        menu.addSeparator()
        self.auto_light_action = menu.addAction("Auto light for unlit scenes")
        self.auto_light_action.setCheckable(True)
        self.auto_light_action.setChecked(options.hdue_viewer_light == "auto")
        self.auto_light_action.toggled.connect(self.select_auto_light)
        menu.addSeparator()
        menu.addAction("Camera controls...").triggered.connect(self.show_camera_controls)
        if self.glass_profile:
            menu.addAction("Reload glass profile").triggered.connect(self.glass_profile.reload)
        self.timer = QtCore.QTimer(app)
        self.timer.setTimerType(QtCore.Qt.PreciseTimer)
        self.timer.timeout.connect(self.tick)
        # Readback completion and drawing take separate ticks. A shorter timer
        # prevents their latency from multiplying a 10ms interval while dragging.
        self.timer.start(4)
        return app, self.controller

    def show_camera_controls(self):
        QtWidgets.QMessageBox.information(self.controller._mainWindow, "カメラ操作",
            "ビューポート上で操作します。\n\n"
            "メッシュの選択：左クリック（USD／cook済みUEメッシュ）\n"
            "回転：Alt＋左ドラッグ\n"
            "平行移動：Alt＋中ドラッグ\n"
            "平行移動（中ボタンなし）：Ctrl＋Alt＋左ドラッグ\n"
            "ズーム／前後移動：Alt＋右ドラッグ、またはホイール")

    def set_if_changed(self, key, value):
        view = self.controller._stageView
        if view.GetRendererSetting(key) != value:
            view.SetRendererSetting(key, value)

    def configure_renderer(self):
        view = self.controller._stageView
        if view.GetCurrentRendererId() != PLUGIN:
            return
        if self.materialx_library:
            self.materialx_library.invalidate()
        if self.glass_profile:
            self.glass_profile.invalidate()
        self.set_if_changed("renderMode", self.options.hdue_mode)
        self.set_if_changed("autoViewerLight", self.options.hdue_viewer_light == "auto")
        if self.options.hdue_mode == "realtime":
            self.set_if_changed("lumenEnabled", True)
        self.sync_stage()

    def sync_stage(self):
        controller = self.controller
        if controller._stageView.GetCurrentRendererId() != PLUGIN:
            return
        stage = controller._dataModel.stage
        if stage:
            if self.asset_references:
                self.asset_references.sync()
                warning="; ".join(self.asset_references.warnings)
                if warning and warning!=self.reported_asset_warning:
                    print("hdUE project warning: "+warning,file=sys.stderr,flush=True)
                    controller.statusMessage("hdUE project warning: "+warning)
                self.reported_asset_warning=warning
            materials_valid=True
            if self.materialx_library:
                valid=self.materialx_library.sync()
                materials_valid=materials_valid and valid
                message=self.materialx_library.preparation_error
                if message and message!=self.material_preparation_error:
                    controller.statusMessage("MaterialX: "+message)
                    print("MaterialX preparation required: "+message,file=sys.stderr,flush=True)
                elif not message and self.material_preparation_error:
                    controller.statusMessage("MaterialX graph restored; rendering resumed")
                self.material_preparation_error=message
            if self.glass_profile:
                valid=self.glass_profile.sync()
                materials_valid=materials_valid and valid
                if self.glass_profile.preparation_error:
                    controller.statusMessage("Glass profile: "+self.glass_profile.preparation_error)
            if self.materialx_library or self.glass_profile:
                self.set_if_changed("materialGraphValid",materials_valid)
            self.set_if_changed("sceneLightsEnabled", bool(controller._dataModel.viewSettings.enableSceneLights))
            self.set_if_changed("metersPerUnit", float(UsdGeom.GetStageMetersPerUnit(stage)))
            self.set_if_changed("upAxis", str(UsdGeom.GetStageUpAxis(stage)))
            frame = controller._dataModel.currentFrame
            seconds = 0.0 if frame.IsDefault() else frame.GetValue() / stage.GetTimeCodesPerSecond()
            self.set_if_changed("timeSeconds", float(seconds))

    def select_mode(self, mode):
        self.options.hdue_mode = mode
        controller = self.controller
        controller._stageView.makeCurrent()
        try:
            controller._rendererPluginChanged(PLUGIN)
            self.configure_renderer()
        finally:
            controller._stageView.doneCurrent()

    def select_auto_light(self, enabled):
        self.options.hdue_viewer_light = "auto" if enabled else "off"
        view = self.controller._stageView
        if view.GetCurrentRendererId() == PLUGIN:
            self.set_if_changed("autoViewerLight", enabled)
            view.updateGL()

    def tick(self):
        try:
            self.sync_stage()
            self.runtime.tick()
            view = self.controller._stageView
            if view.GetCurrentRendererId() == PLUGIN:
                stats = view._renderer.GetRenderStats()
                if self.asset_references:
                    self.asset_references.refresh_bounds(self.runtime,stats)
                    # Proxy creation/bounds notices can make stock usdview frame
                    # its initial empty stage and select Free Camera. Restore an
                    # explicitly requested camera after the first native image.
                    if (not self.native_camera_applied and stats.get('nativeAssetInstances')
                            and not stats.get('nativeAssetLoading') and stats.get('frameId')):
                        self.native_camera_applied=True
                        path=self.options.camera
                        stage=self.controller._dataModel.stage
                        desired=stage.GetPrimAtPath(path) if path.IsAbsolutePath() else next(
                            (p for p in stage.Traverse() if p.IsA(UsdGeom.Camera) and p.GetName()==str(path)),None)
                        if desired and desired.IsA(UsdGeom.Camera):
                            self.controller._dataModel.viewSettings.cameraPrim=desired
                            view.updateGL()
                error = stats.get("error", "")
                if stats.get("nativeAssetLoading"):
                    self.asset_loading=True
                    self.controller.statusMessage("hdUE: UEアセット準備待ち {}件 / 配置Prim {}件 — Path Tracer蓄積は準備完了後".format(
                        stats.get("nativeAssetLoading",0),stats.get("nativeAssetInstances",0)))
                elif self.asset_loading and not error:
                    self.asset_loading=False
                    self.controller.statusMessage("hdUE: UEアセット準備完了 — {} Actors / {} Meshes".format(
                        stats.get("nativeActors",0),stats.get("nativeMeshes",0)))
                if stats.get("vtResidencyPhase") == 1:
                    self.residency_preparing = True
                    self.controller.statusMessage("hdUE: UDIM準備中 — ページ {}/{}、割り当て {}/{}（Path Tracer 0 samples）".format(
                        stats.get("vtResidentPages",0),stats.get("vtRequiredPages",0),
                        stats.get("vtReadyMappings",0),stats.get("vtRequiredMappings",0)))
                elif self.residency_preparing and not error:
                    self.residency_preparing = False
                    self.controller.statusMessage("hdUE: UDIM準備完了 — Path Tracer蓄積開始" if stats.get("vtResidencyPhase")==2 else "hdUE: リアルタイム描画")
                if error and error != self.reported_error:
                    self.reported_error = error
                    self.controller.statusMessage("hdUE: " + error)
                    print("hdUE: " + error, file=sys.stderr, flush=True)
        except BaseException:
            self.failure = traceback.format_exc()
            self.timer.stop()
            QtWidgets.QApplication.instance().closeAllWindows()

    def LaunchProcess(self, options, app, controller):
        if options.hdue_test_output:
            if options.hdue_asset_check:
                from asset_test import AssetTest
                self.test = AssetTest(self, options.hdue_test_output)
            elif options.hdue_glass_check:
                from glass_test import GlassTest
                self.test = GlassTest(self, options.hdue_test_output)
            elif options.hdue_opacity_check:
                from opacity_test import OpacityTest
                self.test = OpacityTest(self, options.hdue_test_output)
            elif options.hdue_residency_check:
                from residency_test import ResidencyTest
                self.test = ResidencyTest(self, options.hdue_test_output)
            elif options.hdue_texture_check:
                from texture_test import TextureTest
                self.test = TextureTest(self, options.hdue_test_output)
            elif options.hdue_materialx_check:
                from materialx_test import MaterialXTest
                self.test = MaterialXTest(self, options.hdue_test_output)
            elif options.hdue_scene_check:
                from scene_check import SceneCheck
                self.test = SceneCheck(self, options.hdue_test_output)
            elif options.hdue_camera_benchmark:
                from camera_benchmark import CameraBenchmark
                self.test = CameraBenchmark(self, options.hdue_test_output)
            else:
                from usdview_test import SmokeTest
                self.test = SmokeTest(self, options.hdue_test_output)
            QtCore.QTimer.singleShot(0, self.test.start)
        super().LaunchProcess(options, app, controller)

    def close(self):
        if self.timer:
            self.timer.stop()
        # Also covers exceptions / app.quit(), which can skip closeEvent.
        if self.controller and self.controller._stageView._renderer:
            view = self.controller._stageView
            view.makeCurrent()
            try:
                view.closeRenderer()
            finally:
                view.doneCurrent()
        if self.runtime:
            self.runtime.close()


def main():
    launcher = Launcher()
    try:
        launcher.Run()
    except SystemExit as error:
        if error.code:
            launcher.failure = f"usdview argument parsing failed ({error.code})"
    except BaseException:
        launcher.failure = traceback.format_exc()
    finally:
        try:
            launcher.close()
        except BaseException:
            launcher.failure = (launcher.failure or "") + traceback.format_exc()
    if launcher.failure:
        print(launcher.failure, file=sys.stderr)
        return 1
    if launcher.options and launcher.options.hdue_test_output:
        if not launcher.test_result:
            print("usdview test did not complete", file=sys.stderr)
            return 1
        result = dict(launcher.test_result, passed=True, engine_shutdown=True,
                      runtime_state=launcher.runtime.status().state,
                      ue_initializations=launcher.runtime.initializations,
                      ticks=launcher.runtime.ticks, pid=os.getpid())
        (launcher.options.hdue_test_output / "verified.json").write_text(
            json.dumps(result, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
